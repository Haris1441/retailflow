-- Use the same target database as the loader.
USE DATABASE RETAIL_DWH;
SELECT SOURCE_SYSTEM, BATCH_ID, ENTITY, COUNT(*) AS PHYSICAL_RECORDS
FROM BRONZE.SOURCE_RECORDS
GROUP BY SOURCE_SYSTEM, BATCH_ID, ENTITY
ORDER BY SOURCE_SYSTEM, BATCH_ID, ENTITY;

-- Expect zero rows.
SELECT SOURCE_SYSTEM, ENTITY, SOURCE_RECORD_ID, COUNT(*) AS COPIES
FROM BRONZE.SOURCE_RECORDS
GROUP BY SOURCE_SYSTEM, ENTITY, SOURCE_RECORD_ID
HAVING COUNT(*) > 1;

-- A replay has INSERTED_COUNT = 0 and MATCHED_COUNT = DISTINCT_COUNT.
SELECT RUN_ID, SOURCE_SYSTEM, BATCH_ID, ENTITY_SCOPE, EXTRACTED_COUNT,
       DISTINCT_COUNT, INSERTED_COUNT, MATCHED_COUNT, FINISHED_AT
FROM AUDIT.BRONZE_LOAD_RUNS
ORDER BY FINISHED_AT DESC;
