USE DATABASE RETAIL_DWH;

SELECT config.SOURCE_SYSTEM, config.ENTITY, config.LOAD_STRATEGY,
       config.WATERMARK_FIELD, config.OVERLAP_MINUTES, config.MAX_BACKFILL_DAYS,
       watermark.LAST_SUCCESSFUL_WATERMARK, watermark.LAST_SUCCESSFUL_RUN_ID
FROM CONTROL.ENTITY_CONFIG AS config
LEFT JOIN CONTROL.WATERMARKS AS watermark
  ON config.SOURCE_SYSTEM = watermark.SOURCE_SYSTEM AND config.ENTITY = watermark.ENTITY
ORDER BY config.SOURCE_SYSTEM, config.ENTITY;

SELECT RUN_ID, SOURCE_SYSTEM, ENTITY_SCOPE, LOAD_TYPE, STATUS, STARTED_AT, FINISHED_AT,
       ERROR_MESSAGE
FROM CONTROL.PIPELINE_RUNS
ORDER BY STARTED_AT DESC;
