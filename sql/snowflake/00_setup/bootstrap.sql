-- Run in Snowsight with an authorized setup role. Review identifiers first.
CREATE WAREHOUSE IF NOT EXISTS RETAILFLOW_WH
  WAREHOUSE_SIZE = XSMALL
  AUTO_SUSPEND = 60
  AUTO_RESUME = TRUE
  INITIALLY_SUSPENDED = TRUE
  STATEMENT_TIMEOUT_IN_SECONDS = 300;

CREATE DATABASE IF NOT EXISTS RETAIL_DWH;
CREATE SCHEMA IF NOT EXISTS RETAIL_DWH.BRONZE;
CREATE SCHEMA IF NOT EXISTS RETAIL_DWH.STAGING;
CREATE SCHEMA IF NOT EXISTS RETAIL_DWH.SILVER;
CREATE SCHEMA IF NOT EXISTS RETAIL_DWH.GOLD;
CREATE SCHEMA IF NOT EXISTS RETAIL_DWH.CONTROL;
CREATE SCHEMA IF NOT EXISTS RETAIL_DWH.DATA_QUALITY;
CREATE SCHEMA IF NOT EXISTS RETAIL_DWH.AUDIT;

CREATE TABLE IF NOT EXISTS RETAIL_DWH.BRONZE.SOURCE_RECORDS (
    SOURCE_SYSTEM VARCHAR NOT NULL,
    ENTITY VARCHAR NOT NULL,
    SOURCE_RECORD_ID VARCHAR NOT NULL,
    BUSINESS_KEY VARCHAR NOT NULL,
    BATCH_ID VARCHAR NOT NULL,
    SOURCE_OPERATION VARCHAR NOT NULL,
    SOURCE_EVENT_AT TIMESTAMP_TZ,
    SOURCE_UPDATED_AT TIMESTAMP_TZ,
    SOURCE_EFFECTIVE_AT TIMESTAMP_TZ,
    SOURCE_AVAILABLE_AT TIMESTAMP_TZ NOT NULL,
    EXTRACTED_AT TIMESTAMP_TZ NOT NULL,
    INGESTED_AT TIMESTAMP_TZ NOT NULL DEFAULT CURRENT_TIMESTAMP(),
    RUN_ID VARCHAR NOT NULL,
    RECORD_HASH VARCHAR NOT NULL,
    RAW_PAYLOAD VARIANT NOT NULL,
    CONSTRAINT SOURCE_RECORDS_PK PRIMARY KEY (SOURCE_SYSTEM, ENTITY, SOURCE_RECORD_ID)
);

CREATE TABLE IF NOT EXISTS RETAIL_DWH.AUDIT.BRONZE_LOAD_RUNS (
    RUN_ID VARCHAR NOT NULL,
    SOURCE_SYSTEM VARCHAR NOT NULL,
    BATCH_ID VARCHAR NOT NULL,
    ENTITY_SCOPE VARCHAR NOT NULL,
    EXTRACTED_COUNT NUMBER NOT NULL,
    DISTINCT_COUNT NUMBER NOT NULL,
    INSERTED_COUNT NUMBER NOT NULL,
    MATCHED_COUNT NUMBER NOT NULL,
    FINISHED_AT TIMESTAMP_TZ NOT NULL DEFAULT CURRENT_TIMESTAMP()
);
